/** Phần nghĩa tiếng Anh trong ngoặc của mục phương ngữ, vd. "Bắp ngô (Corn)" => "Corn" */
export function meaningFor(meaning: string, lang: 'vi' | 'en'): string {
  if (lang === 'vi') return meaning;
  const m = /\(([^()]+)\)\s*$/.exec(meaning);
  return m ? m[1] : meaning;
}
