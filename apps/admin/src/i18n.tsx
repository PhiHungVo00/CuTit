export type Lang = 'vi' | 'en';
export type T = (key: Key, vars?: Record<string, string | number>) => string;

const dicts: Record<Lang, Record<Key, string>> = { vi, en };
export function makeT(lang: Lang): T {
  return (key, vars) => (dicts[lang][key] ?? vi[key]).replace(/\{(\w+)\}/g, (m, k: string) => (vars && k in vars ? String(vars[k]) : m));
}

const Ctx = createContext<{ lang: Lang; t: T; toggle: () => void }>({ lang: 'vi', t: makeT('vi'), toggle: () => undefined });
export const useI18n = () => useContext(Ctx);

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLang] = useState<Lang>(initial ?? (typeof navigator !== 'undefined' && !navigator.language.toLowerCase().startsWith('vi') ? 'en' : 'vi'));
  const value = useMemo(() => ({ lang, t: makeT(lang), toggle: () => setLang((l) => (l === 'vi' ? 'en' : 'vi')) }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}
